/** Scale a recipe's ingredient amounts and macros to actual bodyweight. */
export function scaleAmount(ing: Ingredient, weightKg: number): string {
  if (ing.fixed) return ing.fixed
  if (ing.gPerKg) return `${Math.round(ing.gPerKg * weightKg)} g`
  return ''
}

export function scaleMacros(r: Recipe, weightKg: number) {
  const f = weightKg / REFERENCE_KG
  return {
    kcal: Math.round(r.kcal * f),
    proteinG: Math.round(r.proteinG * f),
    carbG: Math.round(r.carbG * f),
    fatG: Math.round(r.fatG * f),
  }
}
